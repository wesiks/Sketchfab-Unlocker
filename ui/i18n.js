const I18N_LANGS = { es: "Español", en: "English", ru: "Русский" };
const I18N_DEFAULT = "es";
let currentLang = I18N_DEFAULT;

function t(key, vars) {
  const dict = I18N[currentLang] || I18N[I18N_DEFAULT];
  let s = dict[key] ?? I18N[I18N_DEFAULT][key] ?? key;
  if (vars) {
    for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
  }
  return s;
}

function applyI18n(root) {
  const scope = root || document;
  scope.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  scope.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = t(el.dataset.i18nTitle); });
  scope.querySelectorAll("[data-i18n-placeholder]").forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  document.documentElement.lang = currentLang;
}

function setLanguage(lang, persist) {
  if (!I18N[lang]) lang = I18N_DEFAULT;
  currentLang = lang;
  applyI18n();
  if (typeof onLanguageChanged === "function") onLanguageChanged();
  if (persist && window.pywebview && window.pywebview.api) {
    window.pywebview.api.set_language(lang).catch(() => {});
  }
}
